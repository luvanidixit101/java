public class Switch {
    public static void main(String[] args){
        int i =50;
        switch(i){
            case 10:
                System.out.println("i is equals to 10");
                break;
            case 20:
                System.out.println("i is equals to 20");
                break;
            default:
                System.out.println("i is not equals to 10 or 20"); 
        }
    }
}
